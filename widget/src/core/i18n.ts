export const DICTS = { en: en as Dict, fr, de, es, it, nl };
export type Lang = keyof typeof DICTS;

/** "fr-CA" → "fr"; an unknown locale → "en". */
export function pickLocale(locale: string): Lang {
  const lang = locale.slice(0, 2).toLowerCase();
  return lang in DICTS ? (lang as Lang) : "en";
}

/** t(key, vars) for a locale: the language's string, else English, else the key itself. */
export function translator(locale: string) {
  const dict: Record<string, string> = DICTS[pickLocale(locale)];
  const fallback: Record<string, string> = en;
  return (key: string, vars?: Record<string, string | number>): string =>
    (dict[key] ?? fallback[key] ?? key).replace(/\{(\w+)\}/g, (m, v: string) => (vars && v in vars ? String(vars[v]) : m));
}
